export function colorCssVarName(name: ColorName): string {
  if (name.startsWith('color-')) {
    return `--${name}`;
  }
  return `--color-${name}`;
}

export function buildCssVariables(): Record<string, string> {
  const vars: Record<string, string> = {};

  (Object.entries(colors) as Array<[ColorName, string]>).forEach(([name, value]) => {
    vars[colorCssVarName(name)] = value;
  });

  (Object.entries(typography) as Array<[TypographyName, TypographyToken]>).forEach(
    ([name, token]) => {
      vars[`--font-family-${name}`] = token.fontStack;
      vars[`--font-size-${name}`] = token.fontSize;
      vars[`--font-weight-${name}`] = String(token.fontWeight);
      vars[`--line-height-${name}`] = token.lineHeight;
      if (token.letterSpacing) {
        vars[`--letter-spacing-${name}`] = `${token.letterSpacing}px`;
      }
    },
  );

  (Object.entries(spacing) as Array<[SpacingName, string]>).forEach(([name, value]) => {
    vars[`--spacing-${name}`] = value;
  });

  (Object.entries(radius) as Array<[RadiusName, string]>).forEach(([name, value]) => {
    vars[`--${name}`] = value;
  });

  (Object.entries(shadows) as Array<[ShadowName, ShadowToken]>).forEach(([name, token]) => {
    vars[`--shadow-${name}`] = token.css;
    vars[`--shadow-${name}-blur`] = `${token.blur}px`;
  });

  return vars;
}

